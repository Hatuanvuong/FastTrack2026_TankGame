Map::Map()
{
    Initialize();
}

void Map::Initialize()
{
    for (int row = 0; row < Constants::MAP_ROWS; ++row)
    {
        for (int col = 0; col < Constants::MAP_COLS; ++col)
        {
            m_tiles[row][col] = static_cast<TileType>(MAP_LAYOUT[row][col]);
        }
    }
}

TileType Map::GetTile(int row, int col) const
{
    return m_tiles[row][col];
}

int Map::GetRows() const
{
    return Constants::MAP_ROWS;
}

int Map::GetCols() const
{
    return Constants::MAP_COLS;
}